def pass1_tracks_head(dets):
    """The pre-pass with the head's bidirectional probability as the cost:
    pairs within GATE_UM, cost 1 - h_fused, one Hungarian stage, assignments
    kept at h >= P1_HEAD_MIN. Same outputs as pass1_tracks."""
