"""hrefine.py -> hrefinezh.py: the placement head applied to the Zebrahub crops, a THIRD embryo with dense labels.

WHY (2026-09-23). hrefine v1 (6bba-only training) placed 6bba's annotated cells closer to their annotation out of
fold (1.27 -> 1.08 um) and made 44b6 worse (7 of 12 movies). The hidden test is an embryo neither head has seen,
and the two competition embryos give one cross-embryo reading each. Zebrahub (the user, 2026-09-23: "在zebrahub上面
测呢") is the third embryo on record: 41 competition-shaped crops (resampled to the competition voxel grid, so the
head's receptive field is the same size in um), dense machine-generated labels (Ultrack tracks, the same tool
behind the competition's annotation; ~2.5% of cells unlabelled, ~10% of points on near-background intensity --
reference.md), and hpara detections in biohub-zhhpcache (zhdet_hp_<stem>.npz, c{t}/s{t} + the label arrays).

This kernel re-uses hrefine.py's crop / matching / augmentation code verbatim (cut from the file, not retyped) and
v2's saved weights (biohub-hrefine: hrefine_fold{0..4}.pt = the joint heads, hrefine_x6.pt = 6bba only,
hrefine_x44.pt = 44b6 only): for every primary within 7 um of a dense label (greedy 1:1 per frame) it reports the
distance before (hpara) and after each head -- joint = the mean of the five fold models (none saw Zebrahub), x6,
x44 -- by class (isolated / crowded, score, starting distance, movie), the share placed worse, per-crop gains, and
writes zhdet_hr_<stem>.npz (every primary re-placed by the joint head, labels carried through) in case a
Zebrahub solve is wanted later. No training here.

Attach: kernel outputs biohub-zebrahub-extract (crops/*.npz, the images), biohub-zhhpcache (zhdet_hp_),
biohub-hrefine (the weights; v2 must be COMPLETE). GPU T4, ~30 min.
"""
