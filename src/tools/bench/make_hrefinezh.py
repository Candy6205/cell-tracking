HEADS = {"joint": [load(f"hrefine_fold{k}") for k in range(5)], "x6": [load("hrefine_x6")], "x44": [load("hrefine_x44")]}


def predict_arr(models, X, res, s):
    """4-rotation average over every model in the list, inverse-transformed; X float32 crops (N, NCH, W, W)."""
    acc = np.zeros((len(X), 3), np.float32)
    with torch.no_grad():
        for model in models:
            for k in range(4):
                xk, rk, _ = augment(X, res, res, k, False)
                for a in range(0, len(xk), 1024):
                    g = np.concatenate([rk[a:a + 1024], s[a:a + 1024, None]], 1).astype(np.float32)
                    pk = model(torch.from_numpy(xk[a:a + 1024]).to(dev), torch.from_numpy(g).to(dev)).cpu().numpy()
                    acc[a:a + 1024] += inv_vec(pk, k, False)
    return acc / (4 * len(models))


t_all = time.time()
ROWS = []
DUP = dict(before=0, after=0, frames=0)
for k_, name in enumerate(sorted(ZH_HP)):
    t0 = time.time()
    z = np.load(ZH_HP[name])
