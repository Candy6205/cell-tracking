def q(v, p):
    v = v[np.isfinite(v)]
    return float(np.percentile(v, p)) if len(v) else float("nan")


def line(lbl, msk):
    n = int(msk.sum())
    if n == 0:
        print(f"  {lbl:<30} n 0", flush=True)
        return
    b, rf = P.d_before.values[msk], P.d_refine.values[msk]
    s = f"  {lbl:<30} n {n:>7,}  before {q(b, 50):.3f} / {q(b, 90):.3f}  centroid {q(rf, 50):.3f} / {q(rf, 90):.3f}"
    for h in HEADS:
        a = P[f"d_{h}"].values[msk]
        s += f"  | {h} {q(a, 50):.3f} / {q(a, 90):.3f} worse {np.mean(a > b):.3f}"
        a = P[f"d_{h}xy"].values[msk]
        s += f" xy-only {q(a, 50):.3f} worse {np.mean(a > b):.3f}"
    print(s, flush=True)


