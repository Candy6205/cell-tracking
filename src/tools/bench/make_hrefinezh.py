WEIGHTS = _walk_files(lambda fn: fn[:-len(".pt")] if fn.startswith("hrefine_") and fn.endswith(".pt") else None)
print(f"zhdet_hp caches {len(ZH_HP)}, crops {len(CROPS)}, weights {sorted(WEIGHTS)}", flush=True)
