def solve_one(dets, T, seeds, feats, model, cols):
    """rankwhy.solve_one with the model, its columns and the (joined)
    features as parameters. Everything up to and including the ILP, plus
    the sub-threshold repair pool. The post-link stages run in patch_final."""
    if model is None:                      # head-only: the column IS p
        probs = [np.nan_to_num(rows[:, cols], nan=0.0).astype(float)
                 if len(pairs) else np.zeros(0)
                 for pairs, rows, P, C in feats]
    else:
        probs = [model.predict_proba(rows[:, cols])[:, 1]
                 if len(pairs) else np.zeros(0)
                 for pairs, rows, P, C in feats]
    coords_rows, offset, n_glob = [], {}, 0
    for t in range(T):
        c, s_ = seeds[t]
        offset[t] = n_glob
        n_glob += len(c)
        for xyz in c:
            coords_rows.append([t, xyz[0], xyz[1], xyz[2]])
    coords = np.asarray(np.round(coords_rows), np.int16)
    cand_edges = []
    for t in range(T - 1):
        pairs, rows, P, C = feats[t]
        for (i_, j_), pr in zip(pairs, probs[t]):
            if pr >= ILP_FLOOR:
                cand_edges.append((offset[t] + i_, offset[t + 1] + j_,
                                   float(pr), 0.0))
    graph = PIPE.build_graph(coords, cand_edges)
    if graph.num_edges() > 0:
        solver = td.solvers.ILPSolver(
            edge_weight=-1.0 * td.EdgeAttr("edge_prob"),
            appearance_weight=0.0,
            disappearance_weight=ILP_DISAPP,
            division_weight=DIV_W)
        with PIPE.suppress_output():
            graph = solver.solve(graph)
    na = graph.node_attrs(attr_keys=["node_id", "t", "z", "y", "x"])
    nid_l = [int(v) for v in na["node_id"].to_list()]
    remap = {v: i for i, v in enumerate(nid_l)}
    nodes_arr = np.stack([np.asarray(na[c_].to_list(), float)
                          for c_ in ("t", "z", "y", "x")], axis=1)
    rows_e, dropped = [], 0
    if graph.num_edges() > 0:
        ea = graph.edge_attrs(attr_keys=["source_id", "target_id"])
        for a_, b_ in zip(ea["source_id"].to_list(),
                          ea["target_id"].to_list()):
            ra, rb = remap.get(int(a_)), remap.get(int(b_))
            if ra is None or rb is None:
                dropped += 1
                continue
            rows_e.append([ra, rb])
    if dropped:
        warn_once("ilp_endpoint_missing",
                  f"{dropped} solved edges had an endpoint absent from "
                  f"node_attrs and were dropped -> a LOWER BOUND")
    e2 = np.array(rows_e, int) if rows_e else np.zeros((0, 2), int)
    nodes0 = {i_ + 1: {"t": int(nodes_arr[i_, 0]),
                       "xyz": nodes_arr[i_, 1:].astype(float)}
              for i_ in range(len(nodes_arr))}
    edges0 = [(int(a_) + 1, int(b_) + 1) for a_, b_ in e2]
    cand, cand_sc, cand_trees = [], [], []
    for t in range(T):
        c_all = np.asarray(dets[t][0], float)
        s_all = np.asarray(dets[t][1], float)
        cm = (s_all >= CAND_THR) & (s_all < UNET_THRESH)
        cand.append(c_all[cm])
        cand_sc.append(s_all[cm])
        cand_trees.append(cKDTree(cand[-1] * SCALE) if len(cand[-1])
                          else None)
    del graph, probs
    return nodes0, edges0, (cand, cand_sc, cand_trees)


GAP2_STATS = defaultdict(lambda: [0, 0, 0, 0, 0, 0])   # (arm, domain) -> [cands, ctx_rejected, selected, cap_skipped, pool_used, nodes_added]


def _gap2_strict(nodes, edges, next_id, mode, require_ctx, cand, cand_trees, stat):
    """recover_strict_gap2 from the 0.948 notebook, on the harness graph
    (nodes {id: {"t", "xyz" voxel}}, edges [(a, b)]). mode "interp" inserts
    the two interpolated points; "pool" replaces each by the nearest
    sub-gate candidate within GAP2_POOL_UM when one exists. Returns next_id."""
    if not edges or not nodes:
        return next_id
    outgoing = defaultdict(int)
    incoming = defaultdict(int)
    succ, pred = {}, {}
    for a, b in edges:
        outgoing[a] += 1
        incoming[b] += 1
        succ[a] = b if outgoing[a] == 1 else None      # single successor only
        pred[b] = a if incoming[b] == 1 else None
    ends_by_t, starts_by_t = defaultdict(list), defaultdict(list)
    for nid, v in nodes.items():
        if outgoing[nid] == 0:
            ends_by_t[v["t"]].append(nid)
        if incoming[nid] == 0:
            starts_by_t[v["t"]].append(nid)
    pos = {nid: v["xyz"] * SCALE for nid, v in nodes.items()}
    cap = min(GAP2_MAX_LINKS_ABS, max(1, int(round(len(edges) * GAP2_MAX_LINKS_FRAC))))
    proposals = []
    for t in sorted(ends_by_t):
        end_ids = ends_by_t[t]
        start_ids = starts_by_t.get(t + 3, [])
        if not end_ids or not start_ids:
            continue
        S = np.stack([pos[s_] for s_ in start_ids])
        tree = cKDTree(S)
        for e in end_ids:
            ep = pos[e]
            for k in tree.query_ball_point(ep, GAP2_MAX_TOTAL_UM):
                st = start_ids[k]
                sp = pos[st]
                dist = float(np.linalg.norm(sp - ep))
                if dist > GAP2_MAX_TOTAL_UM or dist / 3.0 > GAP2_MAX_STEP_UM:
                    continue
                step = (sp - ep) / 3.0
                step_n = float(np.linalg.norm(step))
                ok, pen = False, 0.0
                pv = pred.get(e)
                if pv is not None:
                    ps = ep - pos[pv]
                    pn = float(np.linalg.norm(ps))
                    if pn <= 0.01 or step_n <= 0.01:
                        ok = True
                    else:
                        cos = float(np.dot(ps, step) / (pn * step_n + 1e-9))
                        if cos > GAP2_COS_MIN and np.linalg.norm(ps - step) <= GAP2_STEP_DIFF_UM:
                            ok = True
                        pen += max(0.0, 0.25 - cos)
                nx = succ.get(st)
                if nx is not None:
                    ns = pos[nx] - sp
                    nn = float(np.linalg.norm(ns))
                    if nn <= 0.01 or step_n <= 0.01:
                        ok = True
                    else:
                        cos = float(np.dot(ns, step) / (nn * step_n + 1e-9))
                        if cos > GAP2_COS_MIN and np.linalg.norm(ns - step) <= GAP2_STEP_DIFF_UM:
                            ok = True
                        pen += max(0.0, 0.25 - cos)
                stat[0] += 1
                if require_ctx and not ok:
                    stat[1] += 1
                    continue
                proposals.append((dist + 2.0 * pen, e, st, t, dist))
    proposals.sort(key=lambda it: it[0])
    selected, used_e, used_s, per_frame = [], set(), set(), defaultdict(int)
    for pr in proposals:
        if len(selected) >= cap:
            stat[3] += 1
            break
        _, e, st, t, _d = pr
        if e in used_e or st in used_s:
            continue
        fcap = max(1, int(round(len(ends_by_t[t]) * GAP2_FRAME_FRAC_CAP)))
        if per_frame[t] >= fcap:
            continue
        selected.append(pr)
        used_e.add(e)
        used_s.add(st)
        per_frame[t] += 1
    used_pool = set()
    for _, e, st, t, _d in selected:
        a_xyz, b_xyz = nodes[e]["xyz"], nodes[st]["xyz"]
        prev = e
        for k in (1, 2):
            mid_t = t + k
            xyz = a_xyz + (b_xyz - a_xyz) * (k / 3.0)
            if mode == "pool" and mid_t < len(cand) and cand_trees[mid_t] is not None:
                dd, ci = cand_trees[mid_t].query(xyz * SCALE)
                if dd <= GAP2_POOL_UM and (mid_t, int(ci)) not in used_pool:
                    xyz = np.asarray(cand[mid_t][int(ci)], float)
                    used_pool.add((mid_t, int(ci)))
                    stat[4] += 1
            nodes[next_id] = {"t": mid_t, "xyz": np.asarray(xyz, float)}
            edges.append((prev, next_id))
            prev = next_id
            next_id += 1
            stat[5] += 1
        edges.append((prev, st))
        stat[2] += 1
    return next_id


def patch_final(nodes0, edges0, pool, out_path, gap2=None, stat=None):
    """rankwhy.patch_final verbatim: the four post-link stages on a FRESH
    COPY, write the geff, return the final graph."""
    cand, cand_sc, cand_trees = pool
    nodes = {g: {"t": v["t"], "xyz": v["xyz"].copy()}
             for g, v in nodes0.items()}
    edges = list(edges0)
    nid2 = len(nodes) + 1
    nid2 = _gap_close(nodes, edges, cand, cand_sc, cand_trees, nid2)
    if gap2 is not None:
        mode, require_ctx = gap2
        nid2 = _gap2_strict(nodes, edges, nid2, mode, require_ctx, cand, cand_trees, stat)
    nodes, edges = _short_filter(nodes, edges)
    _linefit(nodes, edges)
    _add_safe_divisions(nodes, edges)
    ids = sorted(nodes)
