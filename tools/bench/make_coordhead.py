def q3(v):
    v = np.asarray(v, float)
    v = v[np.isfinite(v)]
    if not len(v):
        return "n 0"
    return f"p50 {np.percentile(v, 50):.3f} p90 {np.percentile(v, 90):.3f} within2 {np.mean(v <= 2.0):.3f}"


def fit_head(X, Y, seed=0, epochs=None, lr=None, batch=None):
    """their head on standardised features; smooth-L1 on the bounded shift against the offset (um)"""
    torch.manual_seed(seed)
    mu = X.mean(0)
    sd = X.std(0) + 1e-6
    Xt = torch.from_numpy((X - mu) / sd).float().to(device)
    Yt = torch.from_numpy(Y).float().to(device)
    head = make_head().to(device)
    epochs, lr, batch = epochs or EPOCHS, lr or LR, batch or BATCH
    opt = torch.optim.Adam(head.parameters(), lr=lr)
    n = len(Xt)
    for ep_ in range(epochs):
        perm = torch.randperm(n, device=device)
        for a in range(0, n, batch):
            b = perm[a:a + batch]
            loss = torch.nn.functional.smooth_l1_loss(bounded(head, Xt[b]), Yt[b])
            opt.zero_grad()
            loss.backward()
            opt.step()
    head.eval()
    return head, mu, sd


def apply_head(head, mu, sd, X):
    with torch.no_grad():
        out = []
        for a in range(0, len(X), 65536):
            xt = torch.from_numpy((X[a:a + 65536] - mu) / sd).float().to(device)
            out.append(bounded(head, xt).cpu().numpy())
    return np.concatenate(out) if out else np.zeros((0, 3), np.float32)


