def make_head():
    head = torch.nn.Sequential(torch.nn.Linear(224, 32), torch.nn.SiLU(), torch.nn.Linear(32, 3))
    torch.nn.init.zeros_(head[-1].weight)
    torch.nn.init.zeros_(head[-1].bias)
    return head


def bounded(head, x):
    """their bound: 2 d / (1 + |d|), so the shift stays under 2 um"""
    delta = head(x)
    return BOUND_UM * delta / (1.0 + torch.linalg.vector_norm(delta, dim=-1, keepdim=True))


def tri_sample(fm, q):
    """fm (C, Z, Y, X); q (n, 3) float lattice coords -> (n, C), trilinear, clamped at the border"""
    out = torch.zeros((len(q), fm.shape[0]), device=fm.device, dtype=fm.dtype)
    q = q.clone()
    for ax, size in enumerate(fm.shape[-3:]):
        q[:, ax].clamp_(0, size - 1)
    low = q.floor().long()
    frac = (q - low).to(fm.dtype)
    for dz in (0, 1):
        for dy in (0, 1):
            for dx in (0, 1):
                sh = torch.tensor([dz, dy, dx], device=fm.device)
                loc = low + sh
                for ax, size in enumerate(fm.shape[-3:]):
                    loc[:, ax].clamp_(0, size - 1)
                w = torch.where(sh.bool(), frac, 1 - frac).prod(dim=1)
                out += fm[:, loc[:, 0], loc[:, 1], loc[:, 2]].T * w[:, None]
    return out


def feats224(fm, q):
    """their sample_features at (possibly fractional) lattice coords q: the centre feature and the six neighbour differences"""
    blocks = [tri_sample(fm, q + torch.tensor(o, device=fm.device, dtype=q.dtype)) for o in OFFSETS]
    return torch.cat([blocks[0]] + [b - blocks[0] for b in blocks[1:]], dim=1)


def lattice_peak(det, q):
    """det (Z, Y, X) detection logits; q (n, 3) float lattice coords. The integer lattice point with the highest logit in the
    3 x 3 x 3 block around round(q): the detection their pipeline would have made for this cell."""
    base = q.round().long()
    best = torch.full((len(q),), -float("inf"), device=det.device)
    out = base.clone()
    for dz in (-1, 0, 1):
        for dy in (-1, 0, 1):
            for dx in (-1, 0, 1):
                loc = base + torch.tensor([dz, dy, dx], device=det.device)
                for ax, size in enumerate(det.shape[-3:]):
                    loc[:, ax].clamp_(0, size - 1)
                v = det[loc[:, 0], loc[:, 1], loc[:, 2]].float()
                m = v > best
                best = torch.where(m, v, best)
                out[m] = loc[m]
    return out


class Cap:
    """one forward pass over one movie: our primaries injected as detections, the 224 features captured for the selected
    nodes of every frame at its FIRST occurrence (frame 0 as the first of its window, every later frame as the second:
    where their refine reads unet_out), the edge head stubbed out."""

    def __init__(self, name, prim, sel):
        self.name, self.sel = name, sel
        self.full = [p.astype(np.float32) for p in prim]
        self.T = len(prim)
        self.expected = [f for f in range(self.T - 1) if len(self.full[f]) and len(self.full[f + 1])]
        self.calls = 0
        self.L, self.F, self.FL = {}, {}, {}

    def detect(self, det_logits, f, det_threshold, pool_kernel):
        c = self.full[f]
        if len(c) == 0:
            return np.empty((0, 4), dtype=np.float32)
        grid = c / DS[None, :]
        if len(self.sel[f]) and f not in self.L:
            det = det_logits.reshape(det_logits.shape[-3:])
            q = torch.from_numpy(grid[self.sel[f]].astype(np.float32)).to(det.device)
            self.L[f] = lattice_peak(det, q).cpu().numpy()
        return np.concatenate([np.full((len(c), 1), f, np.float32), grid.astype(np.float32)], axis=1)

    def index(self, maps, coords, mask):
        assert self.calls // 2 < len(self.expected), f"{self.name}: more _index_features calls than pairs"
        f = self.expected[self.calls // 2] + (self.calls % 2)
        self.calls += 1
        if f not in self.F and len(self.sel[f]) and f in self.L:
            assert coords.shape[1] == len(self.full[f]), (self.name, f, tuple(coords.shape), len(self.full[f]))
            idx = torch.from_numpy(np.asarray(self.sel[f], np.int64)).to(maps.device)
            with torch.no_grad():
                self.F[f] = feats224(maps[0].float(), coords[0, idx].float()).cpu().numpy().astype(np.float32)
                self.FL[f] = feats224(maps[0].float(), torch.from_numpy(self.L[f]).to(maps.device).float()).cpu().numpy().astype(np.float32)
        return _ORIG_INDEX(maps, coords, mask)

    @staticmethod
    def edges(feat_src, feat_tgt, coords_src, coords_tgt, *rest):
        return torch.zeros((1, feat_src.shape[1], feat_tgt.shape[1]), device=feat_src.device)

